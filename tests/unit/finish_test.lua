local T = dofile((debug.getinfo(1, "S").source:match("^@(.*)/[^/]+$") or ".") .. "/helper.lua")
local Finish = require("afterword/finish")

print("finish")

T.test("the box starts ticked when KOReader's auto mark is on", function()
    T.eq(Finish.default(true, "reading"), true)
    T.eq(Finish.default(true, nil), true)
end)
T.test("the box starts ticked for a book that is already finished", function()
    T.eq(Finish.default(false, "complete"), true)
    T.eq(Finish.default(nil, "complete"), true)
end)
T.test("the box starts unticked otherwise", function()
    T.eq(Finish.default(false, "reading"), false)
    T.eq(Finish.default(nil, nil), false)
    T.eq(Finish.default(false, "abandoned"), false)
end)
T.test("ticked marks an unfinished book finished", function()
    T.eq(Finish.status_after("reading", true), "complete")
    T.eq(Finish.status_after(nil, true), "complete")
    T.eq(Finish.status_after("abandoned", true), "complete")
end)
T.test("ticked on a finished book writes nothing", function()
    T.eq(Finish.status_after("complete", true), nil)
end)
T.test("unticked on a finished book puts it back to reading", function()
    T.eq(Finish.status_after("complete", false), "reading")
end)
T.test("unticked on an unfinished book leaves it alone", function()
    T.eq(Finish.status_after("reading", false), nil)
    T.eq(Finish.status_after(nil, false), nil)
    T.eq(Finish.status_after("abandoned", false), nil)
end)

T.done()
