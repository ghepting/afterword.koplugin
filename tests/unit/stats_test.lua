local T = dofile((debug.getinfo(1, "S").source:match("^@(.*)/[^/]+$") or ".") .. "/helper.lua")
local Stats = require("afterword/stats")

print("stats")
local DAY = 86400

T.test("days from the first page to the last, whole days, at least one", function()
    T.eq(Stats.span_days(0, 23 * DAY), 23)
    T.eq(Stats.span_days(0, 23 * DAY + 1), 24)
    T.eq(Stats.span_days(100, 100), 1)
    T.eq(Stats.span_days(0, 60), 1)
end)
T.test("days are unknown when a time is missing or backwards", function()
    T.eq(Stats.span_days(nil, 5), nil)
    T.eq(Stats.span_days(5, nil), nil)
    T.eq(Stats.span_days(10, 5), nil)
end)
T.test("how long it took, in weeks and days", function()
    T.eq(Stats.span_text(1), "1 day")
    T.eq(Stats.span_text(5), "5 days")
    T.eq(Stats.span_text(7), "1 week")
    T.eq(Stats.span_text(9), "1 week, 2 days")
    T.eq(Stats.span_text(23), "3 weeks, 2 days")
    T.eq(Stats.span_text(14), "2 weeks")
    T.eq(Stats.span_text(nil), nil)
end)
T.test("time reading, in hours and minutes", function()
    T.eq(Stats.duration_text(21 * 3600 + 40 * 60), "21 h 40 m")
    T.eq(Stats.duration_text(45 * 60), "45 m")
    T.eq(Stats.duration_text(2 * 3600), "2 h")
    T.eq(Stats.duration_text(59), nil)
    T.eq(Stats.duration_text(nil), nil)
end)
T.test("pages a day over the days it took, rounded", function()
    T.eq(Stats.pages_per_day({ read_pages = 736, first_read = 0, finished = 23 * DAY }), 32)
    T.eq(Stats.pages_per_day({ read_pages = 100, first_read = 0, finished = 60 }), 100) -- a day at least
    T.eq(Stats.pages_per_day({ read_pages = 0, first_read = 0, finished = DAY }), nil)
    T.eq(Stats.pages_per_day({ first_read = 0, finished = DAY }), nil)
end)
T.test("the lines to show leave out what cannot be known", function()
    local full = Stats.lines({ read_seconds = 21 * 3600 + 40 * 60, read_pages = 736, first_read = 0, finished = 23 * DAY })
    T.eq(#full, 3)
    T.eq(full[1].label .. ": " .. full[1].value, "Read in: 3 weeks, 2 days")
    T.eq(full[2].label .. ": " .. full[2].value, "Time reading: 21 h 40 m")
    T.eq(full[3].label .. ": " .. full[3].value, "Pace: 32 pages a day")
    local sparse = Stats.lines({ read_seconds = 30 * 60 })
    T.eq(#sparse, 1)
    T.eq(sparse[1].label, "Time reading")
    T.eq(#Stats.lines({}), 0)
end)

T.done()
